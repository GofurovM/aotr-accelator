"""tools/gen_anchors.py <reference game.dat> <src folder> - writes src/aotr_anchors.inc.

Every game.dat address the DLL's source names (in code or in comments) that lies in .text or .rdata, with the 16 bytes
the verified build (AOTR's RotWK 2.02 delayfix game.dat) holds there. aotr_accel.cpp uses the table for a game.dat it
does not know by its .text hash but that has the same header: when every anchor still holds the verified bytes, the
build only differs somewhere this DLL never looks (AOTR 10 changed 15 bytes in the AI's target search), so the parts
tied to addresses may run there too. Each part still checks its own bytes before it patches. Run it again whenever a
new address is used.

v85: the import address table is left out (the loader fills it at run time, so it never holds the file's bytes - in
v72-v84 its 10 anchors made every unknown build look changed), and each anchor carries a mask of the source files that
name it: aotr_accel.cpp turns off only the parts whose own places changed."""
import re, struct, sys, glob, os
ref, src = sys.argv[1], sys.argv[2]
d = open(ref, 'rb').read()
pe = struct.unpack_from('<I', d, 0x3c)[0]; n = struct.unpack_from('<H', d, pe + 6)[0]; so = struct.unpack_from('<H', d, pe + 20)[0]; sh = pe + 24 + so
secs = {}
for i in range(n):
    o = sh + 40 * i; name = d[o:o + 8].rstrip(b'\0').decode('latin1'); vs, va, rs, ro = struct.unpack_from('<IIII', d, o + 8)
    secs[name] = (0x400000 + va, min(vs, rs), ro)
def rva_off(rva):
    for i in range(n):
        o = sh + 40 * i; vs, va, rs, ro = struct.unpack_from('<IIII', d, o + 8)
        if va <= rva < va + rs: return ro + rva - va
    return None
# the import address table: every import descriptor's FirstThunk array (filled by the loader at run time)
iat = []
optd = pe + 24; imp_rva = struct.unpack_from('<I', d, optd + 96 + 8)[0]; io = rva_off(imp_rva) if imp_rva else None
while io is not None:
    ft = struct.unpack_from('<I', d, io + 16)[0]
    if not ft: break
    fo = rva_off(ft); k = 0
    while fo is not None and struct.unpack_from('<I', d, fo + 4 * k)[0]: k += 1
    iat.append((0x400000 + ft, 0x400000 + ft + 4 * k + 4)); io += 20
def in_iat(v, k): return any(v < hi and v + k > lo for lo, hi in iat)
def fileoff(v):
    for nm in ('.text', '.rdata'):
        a, l, ro = secs[nm]
        if a <= v < a + l: return ro + (v - a), a + l - v
    return None, 0
addrs = {}                                   # address -> set of the source files that name it
for f in sorted(glob.glob(os.path.join(src, '*.inc')) + glob.glob(os.path.join(src, '*.cpp'))):
    b = os.path.basename(f)
    if b in ('gd_funcs.inc', 'aotr_anchors.inc', 'aotr_start.cpp'): continue
    for m in re.finditer(r'\b0x(00)?([0-9A-Fa-f]{6})\b', open(f, encoding='latin1').read()):
        v = int(m.group(2), 16)
        off, room = fileoff(v)
        if off is not None and not in_iat(v, min(16, room)): addrs.setdefault(v, set()).add(b)
files = sorted(set().union(*addrs.values()))
assert len(files) <= 64, 'more than 64 source files name addresses - widen the mask'
rows = []
for v in sorted(addrs):
    off, room = fileoff(v)
    k = min(16, room)
    mask = sum(1 << files.index(f) for f in addrs[v])
    rows.append('    { 0x%08X, %2d, { %s }, 0x%016Xull },' % (v, k, ', '.join('0x%02X' % b for b in d[off:off + k]), mask))
out = os.path.join(src, 'aotr_anchors.inc')
with open(out, 'w', newline='\r\n') as f:
    f.write('// aotr_anchors.inc - GENERATED by tools/gen_anchors.py from the verified game.dat (do not edit by hand).\n')
    f.write('// Every .text / .rdata address the source names, with the bytes the verified build holds there (see the tool).\n')
    f.write('// files: bit i of an anchor\'s mask = kAnchorFiles[i] names that address. The import address table is left out.\n')
    f.write('static const char* const kAnchorFiles[] = { %s };\n' % ', '.join('"%s"' % x for x in files))
    f.write('struct AotrAnchor { DWORD va; BYTE n; BYTE b[16]; unsigned __int64 files; };\n')
    f.write('static const AotrAnchor kAnchors[] = {\n' + '\n'.join(rows) + '\n};\n')
print(len(rows), 'anchors ->', out)
